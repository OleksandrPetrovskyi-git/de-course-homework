-- Член 'unknown' у dim_driver має бути рівно один після будь-якої кількості запусків.
-- Ловить два збої інкременту: unknown дописується щоразу без видалення (дублі) або зникає
-- (поїздки, скасовані до прийняття, лишаються без ключа). Тест падає, якщо повернеться рядок.
select count(*) as unknown_members
from {{ ref('dim_driver') }}
where driver_key = 'unknown'
having count(*) <> 1
